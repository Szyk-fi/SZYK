"""Converts the Spleen BDF fonts the device itself uses (fonts/spleen_src, BSD-2-Clause,
(c) Frederic Cambus, see site/assets/LICENSE-spleen) into site/js/spleen.js so the web
screen draws text with the identical bitmaps. Printable ASCII only, like the firmware:
anything else renders as a space."""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
sizes = ['6x12', '8x16', '12x24', '16x32']
out = {}
for s in sizes:
    w, h = map(int, s.split('x'))
    lines = (root / f'fonts/spleen_src/spleen-{s}.bdf').read_text().splitlines()
    glyphs, enc, rows, inbmp = {}, None, [], False
    for ln in lines:
        if ln.startswith('ENCODING'): enc = int(ln.split()[1])
        elif ln.startswith('BITMAP'): rows, inbmp = [], True
        elif ln.startswith('ENDCHAR'):
            inbmp = False
            if enc is not None and 32 <= enc <= 126: glyphs[enc] = rows
        elif inbmp and ln.strip():
            v = int(ln.strip(), 16); nb = len(ln.strip()) * 4
            rows.append(v << (((w + 7) // 8) * 8 - nb))   # left-align to whole bytes
    # pack: per glyph, h ints (bit (bytes*8-1-x) = pixel x)
    out[s] = {'w': w, 'h': h, 'g': [glyphs.get(c, [0] * h) for c in range(32, 127)]}
js = '/* generated by site/tools/make_spleen.py: Spleen bitmap fonts, BSD-2-Clause (c) 2018-2026 Frederic Cambus */\nwindow.SPLEEN = ' + json.dumps(out, separators=(',', ':')) + ';\n'
(root / 'site/js/spleen.js').write_text(js)
print(len(js), 'bytes')
